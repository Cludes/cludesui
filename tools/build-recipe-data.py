"""Builds CludesUIForeverEssentials_RecipeData.lua from a NaowhForever folder:
every profession's trainers, ranks and recipes on WoW Forever, with each
recipe's skill thresholds and where it comes from. Reads the file as text and
copies only its table literal; none of its code runs.
Usage: python -I tools/build-recipe-data.py <NaowhForever-x.y.z dir> <out>"""
import os, sys

src, out = sys.argv[1], sys.argv[2]
text = open(os.path.join(src, "NaowhForever_Professions", "Data", "RecipeData.lua"), encoding="utf-8").read().replace("\r\n", "\n")
start = text.index("ns.RecipeData = {") + len("ns.RecipeData = ")
body = text[start:].rstrip()
assert body.startswith("{") and body.endswith("}")
lines = [
    "if CUI_CLIENT_BLOCKED then return end -- pre-12.1 client failsafe (CludesUI_ClientGate.lua)",
    "if not (CludesUI and CludesUI.IS_FOREVER) then return end",
    "-------------------------------------------------------------------------------",
    "--  CludesUIForeverEssentials_RecipeData.lua -- GENERATED by tools/build-recipe-data.py",
    "--  Each profession by skill line: skillSpell, trainers { npc, name, sides,",
    "--  map, x, y }, ranks { cap, skill, cost | item + vendors | quest + teachers }",
    "--  and recipes { spell, item, skill, yellow, grey, recipe, source and where }.",
    "-------------------------------------------------------------------------------",
    "local _, module = ...",
    "",
    "function module.RecipeData()",
    "return " + body,
    "end",
    "",
]
out_text = "\n".join(lines)
assert "NaowhForever" not in out_text and "ns." not in out_text
open(out, "w", encoding="utf-8", newline="\r\n").write(out_text)
print("wrote", len(out_text), "bytes")
