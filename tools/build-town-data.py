"""Builds CludesUIForeverEssentials_TownMapData.lua from a NaowhForever folder:
service NPCs, mailboxes, spirit healers, the capital cities and the maps the
game has under two IDs. Reads the files as text and copies only their table
literals; none of their code runs.
Usage: python -I tools/build-town-data.py <NaowhForever-x.y.z dir> <out>"""
import os, sys

src, out = sys.argv[1], sys.argv[2]

def table(path, name):
    text = open(path, encoding="utf-8").read().replace("\r\n", "\n")
    start = text.index(name + " = {") + len(name) + 3
    depth, i, quote = 0, start, None
    while True:
        c = text[i]
        if quote:
            if c == "\\": i += 1
            elif c == quote: quote = None
        elif c in "\"'": quote = c
        elif c == "{": depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0: return text[start:i + 1]
        i += 1

root = os.path.join(src, "NaowhForever")
qol = os.path.join(src, "NaowhForever_QoL", "Interface")
towns = os.path.join(root, "Shared", "Game", "Towns.lua")
parts = {
    "capitals": table(towns, "ns.TownCapitals"),
    "same": table(os.path.join(root, "Shared", "Data", "SameMaps.lua"), "ns.Shared.SameMaps"),
    "npcs": table(towns, "ns.TownNPCs"),
    "mail": table(os.path.join(qol, "TownMailboxes.lua"), "ns.TownMailboxes"),
    "spirit": table(os.path.join(qol, "TownSpiritHealers.lua"), "ns.TownSpiritHealers"),
}
lines = [
    "if CUI_CLIENT_BLOCKED then return end -- pre-12.1 client failsafe (CludesUI_ClientGate.lua)",
    "if not (CludesUI and CludesUI.IS_FOREVER) then return end",
    "-------------------------------------------------------------------------------",
    "--  CludesUIForeverEssentials_TownMapData.lua -- GENERATED by tools/build-town-data.py",
    "--  Town map places (CludesUIForeverEssentials_TownMap.lua), in percent of each",
    "--  zone map: { x, y, category, name, title, class, factions, npcID }.",
    "--  factions holds A and/or H. Wrapped in a function so the tables are only",
    "--  built on first enable.",
    "-------------------------------------------------------------------------------",
    "local _, module = ...",
    "",
    "function module.TownMapData()",
    "return {",
]
for key in ("capitals", "same", "npcs", "mail", "spirit"):
    lines.append(key + " = " + parts[key] + ",")
lines += ["}", "end", ""]
text = "\n".join(lines)
assert "NaowhForever" not in text and "ns." not in text
open(out, "w", encoding="utf-8", newline="\r\n").write(text)
print("wrote", len(text), "bytes,", parts["npcs"].count("\n        {"), "npcs,",
      parts["mail"].count("\n        {"), "mailboxes,", parts["spirit"].count("\n        {"), "spirit healers")
