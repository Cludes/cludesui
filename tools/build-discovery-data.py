"""Builds the Discovery data files from a NaowhForever folder:
CludesUIForeverEssentials_DiscoveryData.lua (library books, the Cozy Sleeping
Bag chain, the Field Journal) and CludesUIForeverEssentials_QuestData.lua (every
quest and rare by zone). Reads the files as text and rewrites only their
namespace lines; none of their code runs. Each set is wrapped in a function so
its tables are built only when first needed.
Usage: python -I tools/build-discovery-data.py <NaowhForever-x.y.z dir> <out dir>"""
import os, re, sys

src, out = sys.argv[1], sys.argv[2]
disc = os.path.join(src, "NaowhForever_Discovery", "Data")
qdata = os.path.join(src, "NaowhForever_DiscoveryData")

GATE = [
    "if CUI_CLIENT_BLOCKED then return end -- pre-12.1 client failsafe (CludesUI_ClientGate.lua)",
    "if not (CludesUI and CludesUI.IS_FOREVER) then return end",
    "-------------------------------------------------------------------------------",
]

def body(path, renames):
    text = open(path, encoding="utf-8").read().replace("\r\n", "\n")
    lines = text.split("\n")
    if lines and lines[0].startswith("-- "): lines = lines[1:]
    lines = [l for l in lines if not l.startswith("local ns =") and not l.startswith("local D =")]
    text = "\n".join(lines)
    for a, b in renames:
        text = text.replace(a, b)
    return text.strip() + "\n"

def write(name, header, parts):
    text = "\n".join(GATE + header + [
        "-------------------------------------------------------------------------------",
        "local _, module = ...", "",
    ] + parts)
    assert "NaowhForever" not in text and "ns." not in text, name
    open(os.path.join(out, name), "w", encoding="utf-8", newline="\r\n").write(text)
    print("wrote", name, len(text), "bytes")

ren = [("ns.Shared.Items.SLEEPING_BAG", "211527"), ("ns.", "D.")]
write("CludesUIForeverEssentials_DiscoveryData.lua", [
    "--  CludesUIForeverEssentials_DiscoveryData.lua -- GENERATED by tools/build-discovery-data.py",
    "--  The library books on WoW Forever (where each lies, who takes it, the",
    "--  rewards), the Cozy Sleeping Bag's hidden quest chain, and the Field",
    "--  Journal's fish, herbs and dishes.",
], [
    "function module.DiscoveryData()",
    "local D = {}",
    body(os.path.join(disc, "Books.lua"), ren),
    "do",
    body(os.path.join(disc, "SleepingBag.lua"), ren),
    "end",
    body(os.path.join(disc, "FieldJournal.lua"), ren),
    "return D",
    "end", "",
])

write("CludesUIForeverEssentials_QuestData.lua", [
    "--  CludesUIForeverEssentials_QuestData.lua -- GENERATED by tools/build-discovery-data.py",
    "--  Every quest of every zone on WoW Forever with its chain, requirements",
    "--  and giver, and every rare of every zone with its spots and drops.",
], [
    "function module.QuestData()",
    "local D = {}",
    body(os.path.join(qdata, "Quests.lua"), []),
    "return D",
    "end", "",
    "function module.RareData()",
    "local D = {}",
    body(os.path.join(qdata, "Rares.lua"), []),
    "return D",
    "end", "",
])
