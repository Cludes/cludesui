"""Builds CludesUIForeverEssentials_AuctionFeed.lua from a NaowhForever folder:
every Forever auction house's lowest price per item at release, packed as
id:price:listed steps in base 36 per house. Reads the file as text and copies
only its table literal; none of its code runs.
Usage: python -I tools/build-auction-feed.py <NaowhForever-x.y.z dir> <out>"""
import os, sys

src, out = sys.argv[1], sys.argv[2]
text = open(os.path.join(src, "NaowhForever_AuctionData", "Prices.lua"), encoding="utf-8").read().replace("\r\n", "\n")
start = text.index("ns.AuctionFeed = {") + len("ns.AuctionFeed = ")
body = text[start:].rstrip()
assert body.startswith("{") and body.endswith("}")
lines = [
    "if CUI_CLIENT_BLOCKED then return end -- pre-12.1 client failsafe (CludesUI_ClientGate.lua)",
    "if not (CludesUI and CludesUI.IS_FOREVER) then return end",
    "-------------------------------------------------------------------------------",
    "--  CludesUIForeverEssentials_AuctionFeed.lua -- GENERATED by tools/build-auction-feed.py",
    "--  Every WoW Forever auction house's lowest prices when this version was",
    "--  built: time, then regions[region][house] = { faction, prices }, prices as",
    "--  'step:price:listed,...' in base 36 (each item ID the step from the one",
    "--  before). A scan of your own replaces it once newer.",
    "-------------------------------------------------------------------------------",
    "local _, module = ...",
    "",
    "function module.AuctionFeedData()",
    "return " + body,
    "end",
    "",
]
out_text = "\n".join(lines)
assert "NaowhForever" not in out_text and "ns." not in out_text
open(out, "w", encoding="utf-8", newline="\r\n").write(out_text)
print("wrote", len(out_text), "bytes")
