"""Builds CludesUIForeverEssentials_JournalData.lua from a NaowhForever_DungeonJournal
Data folder.
Reads the files as text and rewrites only their namespace lines; none of their
code runs. Usage: python -I tools/build-journal-data.py <NaowhForever_DungeonJournal dir> <out>"""
import glob, os, re, sys

src, out = sys.argv[1], sys.argv[2]
data = os.path.join(src, "Data")

def body(path, heads):
    text = open(path, encoding="utf-8").read().replace("\r\n", "\n")
    lines = text.split("\n")
    # Drop the namespace lines and each source file's own header comment.
    if lines and lines[0].startswith("-- "): lines = lines[1:]
    keep = [l for l in lines if not any(l.startswith(h) for h in heads)]
    text = "\n".join(keep)
    text = text.replace("ns.Journal.", "J.").replace("ns.Shared.ItemFacts", "{}")
    return text.strip() + "\n"

parts = [
    "if CUI_CLIENT_BLOCKED then return end -- pre-12.1 client failsafe (CludesUI_ClientGate.lua)",
    "if not (CludesUI and CludesUI.IS_FOREVER) then return end",
    "-------------------------------------------------------------------------------",
    "--  CludesUIForeverEssentials_JournalData.lua -- GENERATED by tools/build-journal-data.py",
    "--  Every WoW Forever dungeon and raid: bosses in kill order, their loot and",
    "--  drop chances, a tip per boss, and each dungeon's quests and levels.",
    "--  Game data build " + re.search(r'DATA_BUILD = "([^"]+)"', open(os.path.join(data, "Build.lua"), encoding="utf-8").read()).group(1) + ".",
    "-------------------------------------------------------------------------------",
    "local _, module = ...",
    "local J = module.Journal",
    "",
]
heads = ("local ns =", "local J =")
for f in sorted(glob.glob(os.path.join(data, "Dungeons", "*.lua"))):
    parts.append(body(f, heads).replace("J.AddDungeon(", "J.AddDungeon("))
parts.append(body(os.path.join(data, "Tips.lua"), heads))
parts.append(body(os.path.join(data, "Quests.lua"), heads))
parts.append(body(os.path.join(data, "Items.lua"), heads))
text = "\n".join(parts)
assert "NaowhForever" not in re.sub(r"--[^\n]*", "", text), "a namespace line was left"
open(out, "w", encoding="utf-8", newline="\r\n").write(text)
print("wrote", len(text), "bytes,", text.count("J.AddDungeon("), "dungeons")
